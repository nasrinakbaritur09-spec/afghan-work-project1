  /* ================================================
     TRANSLATE REGISTER PAGE
     ================================================ */

  function translateRegisterPage(language) {
    const lang =
      language ||
      window.getCurrentLanguage?.() ||
      localStorage.getItem("afghanWorkLanguage") ||
      "en";

    const dictionary =
      window.translations[lang] ||
      window.translations.en;

    document.documentElement.lang = lang;
    document.documentElement.dir =
      lang === "fa" || lang === "ps" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;

      if (dictionary[key] !== undefined) {
        element.textContent = dictionary[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const key = element.dataset.i18nPlaceholder;

      if (dictionary[key] !== undefined) {
        element.placeholder = dictionary[key];
      }
    });

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      const key = element.dataset.i18nTitle;

      if (dictionary[key] !== undefined) {
        if (element === document.documentElement) {
          document.title = dictionary[key];
        } else {
          element.title = dictionary[key];
        }
      }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      const key = element.dataset.i18nAlt;

      if (dictionary[key] !== undefined) {
        element.alt = dictionary[key];
      }
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      const key = element.dataset.i18nAriaLabel;

      if (dictionary[key] !== undefined) {
        element.setAttribute("aria-label", dictionary[key]);
      }
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
      const active = button.dataset.language === lang;

      button.classList.toggle("active", active);
      button.setAttribute("aria-pressed", String(active));
    });

    // Update password controls and requirements.
    if (typeof window.updatePasswordToggleLanguage === "function") {
      window.updatePasswordToggleLanguage();
    }

    if (typeof window.updatePasswordRules === "function") {
      const password =
        document.querySelector('#registerForm [name="password"]') ||
        document.querySelector("#password");

      if (password) {
        window.updatePasswordRules(password.value);
      }
    }

    if (typeof window.updatePasswordStrength === "function") {
      const password =
        document.querySelector('#registerForm [name="password"]') ||
        document.querySelector("#password");

      if (password) {
        window.updatePasswordStrength(password.value);
      }
    }
  }

  window.translateRegisterPage = translateRegisterPage;

  /* ================================================
     LANGUAGE EVENTS
     ================================================ */

  document.addEventListener("DOMContentLoaded", () => {
    translateRegisterPage();
  });

  window.addEventListener("languageChanged", (event) => {
    translateRegisterPage(event.detail?.language);
  });

